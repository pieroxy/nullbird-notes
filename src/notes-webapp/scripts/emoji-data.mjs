// Writes src/ts/utils/EmojiData.ts, the emoji helper's list (see Emoji.ts), from Unicode's files:
//
//   curl -LO https://www.unicode.org/Public/emoji/latest/emoji-test.txt
//   curl -L -o annotations.xml https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotations/en.xml
//   curl -L -o derived.xml https://raw.githubusercontent.com/unicode-org/cldr/main/common/annotationsDerived/en.xml
//   node scripts/emoji-data.mjs emoji-test.txt annotations.xml derived.xml
//
// Unicode License V3: see src/licenses/unicode.txt. No dependency: run once per Unicode release,
// and the file it writes is checked in.
//
// Kept: the fully-qualified emojis, without their skin-tone variants (five more of most people) and
// the components (skin tones and hair alone). Each with its Emoji version, its name, and the
// keywords CLDR gives it that its name doesn't have, for the search.
import fs from "node:fs";
import path from "node:path";

const [testFile, ...annotationFiles] = process.argv.slice(2);
if (!testFile || annotationFiles.length === 0) {
  console.error("Usage: node scripts/emoji-data.mjs emoji-test.txt annotations.xml [derived.xml]");
  process.exit(1);
}

/** Unicode's groups, in their order: ours, with a label and the emoji on its tab. */
const GROUPS = {
  "Smileys & Emotion": ["smileys", "Smileys and emotion", "😀"],
  "People & Body": ["people", "People and body", "👋"],
  "Animals & Nature": ["animals", "Animals and nature", "🐻"],
  "Food & Drink": ["food", "Food and drink", "🍔"],
  "Travel & Places": ["travel", "Travel and places", "✈️"],
  "Activities": ["activities", "Activities", "⚽"],
  "Objects": ["objects", "Objects", "💡"],
  "Symbols": ["symbols", "Symbols", "❤️"],
  "Flags": ["flags", "Flags", "🏁"],
};
const SKIN_TONE = /[\u{1F3FB}-\u{1F3FF}]/u;
/** CLDR names them without the variation selector. */
const key = (emoji) => emoji.replace(/️/g, "");

const unescape = (text) => text.replace(/&amp;/g, "&").replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&apos;/g, "'");
const keywords = new Map();
for (const file of annotationFiles) {
  for (const [, cp, words] of fs.readFileSync(file, "utf8").matchAll(/<annotation cp="([^"]+)">([^<]*)<\/annotation>/g)) {
    const emoji = key(unescape(cp));
    if (!keywords.has(emoji)) keywords.set(emoji, unescape(words).split("|").map((w) => w.trim().toLowerCase()).filter(Boolean));
  }
}

const groups = [];
let group;
let version;
for (const line of fs.readFileSync(testFile, "utf8").split("\n")) {
  version ??= /^# Version: (\S+)/.exec(line)?.[1];
  const header = /^# group: (.+)$/.exec(line);
  if (header) {
    const known = GROUPS[header[1].trim()];
    group = known ? { id: known[0], label: known[1], icon: known[2], lines: [] } : undefined;
    if (group) groups.push(group);
    continue;
  }
  const entry = /^[0-9A-F ]+; fully-qualified\s+# (\S+) E(\d+\.\d+) (.+)$/.exec(line);
  if (!entry || !group) continue;
  const [, emoji, emojiVersion, name] = entry;
  if (SKIN_TONE.test(emoji)) continue;
  const nameWords = new Set(name.toLowerCase().split(/[^\p{L}\p{N}]+/u));
  const extra = (keywords.get(key(emoji)) ?? []).filter((w) => !w.split(/[^\p{L}\p{N}]+/u).every((part) => !part || nameWords.has(part)));
  group.lines.push([emoji, emojiVersion, name, extra.join(" ")].join("\t"));
}
const missing = Object.keys(GROUPS).length - groups.length;
if (missing) throw new Error(missing + " groups not found in " + testFile);

const out = path.join(path.dirname(new URL(import.meta.url).pathname), "../src/ts/utils/EmojiData.ts");
fs.writeFileSync(out, `// Generated by scripts/emoji-data.mjs from Unicode's emoji-test.txt (Emoji ${version}) and CLDR's
// English annotations. Unicode License V3: see src/licenses/unicode.txt. Don't edit: regenerate.

/** Per group: its ID, label, tab emoji, then a line per emoji: emoji, Emoji version, name, keywords, tab-separated. */
export const EMOJI_DATA: [id: string, label: string, icon: string, emojis: string][] = [
${groups.map((g) => "  " + JSON.stringify([g.id, g.label, g.icon, g.lines.join("\n")]) + ",").join("\n")}
];
`);
console.log("Emoji " + version + ": " + groups.reduce((n, g) => n + g.lines.length, 0) + " emojis in " + out);
